GRADES = (5, 6)


def take(pool, n, exclude=()):
    cand = [x for x in pool if x not in exclude]
    random.shuffle(cand)
    return cand[:n]


def gen_poems():
    """上下句接续 + 诗句作者。"""
    downs = [p[1] for p in D.POEMS]
    authors = sorted({p[2] for p in D.POEMS} - {"汉乐府", "北朝民歌"})
    n = 0
    for up, down, author, title in D.POEMS:
        others = [x for x in downs if x != down]
        # 同篇的其它句子不能当干扰项，否则容易被“排序”猜对
        same = [p[1] for p in D.POEMS if p[3] == title]
        pool = [x for x in others if x not in same]
        for g in GRADES:
            add(g, "“%s”的下一句是？" % up, down, take(pool, 3, [down]),
                "出自%s《%s》。" % (author, title))
            n += 1
            if author not in ("汉乐府", "北朝民歌"):
                add(g, "“%s”的作者是？" % up, author,
                    take(authors, 3, [author]), "出自%s《%s》。" % (author, title))
                n += 1
    return n


def gen_idioms():
    """成语→释义，以及释义→成语（反向）。"""
    meanings = [x[1] for x in D.IDIOMS]
    names = [x[0] for x in D.IDIOMS]
    n = 0
    for word, means in D.IDIOMS:
        for g in GRADES:
            add(g, "“%s”的意思是？" % word, means, take(meanings, 3, [means]),
                "%s：%s。" % (word, means))
            n += 1
            add(g, "下面哪个成语表示“%s”？" % means, word, take(names, 3, [word]),
                "“%s”的意思是：%s。" % (word, means))
            n += 1
    return n


def gen_antonyms():
    """正反两向都出，同语义簇的词不当干扰项。"""
    words = [x[0] for x in D.ANTONYMS] + [x[1] for x in D.ANTONYMS]
    n = 0
    for a, b, cluster in D.ANTONYMS:
        blocked = {a, b} | {w for x in D.ANTONYMS if x[2] == cluster for w in x[:2]}
        wrongs_pool = [w for w in words if w not in blocked]
        for g in GRADES:
            add(g, "“%s”的反义词是？" % a, b, take(wrongs_pool, 3), "“%s”与“%s”意思相反。" % (a, b))
            n += 1
            add(g, "“%s”的反义词是？" % b, a, take(wrongs_pool, 3), "“%s”与“%s”意思相反。" % (b, a))
            n += 1
    return n


