def add(grade, q, correct, wrongs, why, level=1):
    opts = [str(correct)]
    for w in wrongs:
        w = str(w)
        if w not in opts:
            opts.append(w)
    if len(opts) != 4:
        print("skip (opts=%d): %s" % (len(opts), q))
        return
    key = (grade, q)
    if key in SEEN:
        print("skip (dup): %s" % q)
        return
    SEEN.add(key)
    random.shuffle(opts)
    BANK.append({
        "id": "yw-%d-%03d" % (grade, len(BANK)),
        "grade": grade,
        "subject": "语文",
        "q": q,
        "o": opts,
        "a": opts.index(str(correct)),
        "why": why,
        "level": level,
    })


